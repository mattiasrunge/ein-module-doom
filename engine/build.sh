#!/bin/sh
# Builds Crispy Doom's three games to WebAssembly for the module's engine worker: doom, heretic and
# hexen, each an ES module glue (<game>.js) and its wasm, single-threaded, with no SDL, no DOM and
# no main loop (ein_main.c, ein_video.c); and the server of the games EiN hosts, which the
# doom-server service runs in a worker (doom-server.js and its wasm, ein_server.c). Run in the emsdk image by engine/Containerfile, from a
# directory holding crispy/ (Crispy Doom with the patches here applied), SDL/ (SDL 2's headers, which the
# sources include; no SDL is linked) and ein/ (this directory's C files and config.h). Writes the
# builds to the directory named by its argument. EXTRA_LDFLAGS are added to each link, such as
# --profiling-funcs to name the functions in a stack trace.
set -eu

out=$1
rm -rf obj
mkdir -p "$out" obj/common

# Crispy's files every game shares, but for those this build replaces (i_main.c, i_video.c,
# i_joystick.c, i_endoom.c, i_videohr.c: ein_main.c, ein_video.c, ein_stubs.c), the sound and music
# modules on SDL_mixer, FluidSynth, Windows and the PC speaker (ein_sound.c in their place), the
# true-colour renderer, SDL_net's network (net_ein.c in its place) and the network's text-mode
# screens, Windows' and mmap's WAD files (w_file_stdc.c reads them), the dedicated server's own
# program, and the zone allocator on malloc (z_zone.c's is the one Doom had).
EXCLUDED="i_main i_video i_joystick i_endoom i_videohr i_sdlsound i_sdlmusic i_musicpack i_flmusic
  i_winmusic i_pcsound i_truecolor net_sdl net_gui w_file_win32 w_file_posix d_dedicated
  z_native"

common=""
for file in crispy/src/*.c; do
  name=$(basename "$file" .c)
  case " $(echo $EXCLUDED) " in *" $name "*) continue ;; esac
  common="$common $file"
done
common="$common crispy/opl/opl3.c crispy/opl/opl_queue.c ein/opl_ein.c ein/ein_sound.c ein/ein_video.c ein/ein_sdl.c ein/ein_stubs.c ein/net_ein.c"

# i_sound.c lists the PC speaker's module, which is this build's own (ein_sound.c); with SDL_mixer
# left out it is the only one, and SDL.h, which i_sound.c otherwise has from SDL_mixer.h, is
# included ahead of every file.
CFLAGS="-O2 -w -include SDL.h -DDISABLE_SDL2MIXER -Dsound_pcsound_module=sound_ein_module -Iein -Icrispy/src -Icrispy/opl -Icrispy/textscreen -ISDL/include"

# Two compilers at a time keep the build's memory small beside a running EiN.
jobs=${EMCC_CORES:-2}
echo "$common" | tr ' ' '\n' | grep . | xargs -P "$jobs" -I{} sh -c \
  'emcc $0 -c "$1" -o "obj/common/$(echo "$1" | tr / _).o"' "$CFLAGS" {}

for game in doom heretic hexen; do
  mkdir -p "obj/$game"
  define=$(echo "$game" | tr a-z A-Z)
  ls crispy/src/$game/*.c ein/ein_main.c ein/ein_net.c | xargs -P "$jobs" -I{} sh -c \
    'emcc $0 -DEIN_$1 -Icrispy/src/$2 -c "$3" -o "obj/$2/$(basename "$3" .c).o"' "$CFLAGS" "$define" "$game" {}

  # The glue is an ES module for a worker that runs nothing by itself: the worker starts the game
  # with ein_start. It is headed with Deno's ignore comments, so core's `deno fmt` and `deno lint`
  # pass over the generated file.
  emcc -O2 obj/common/*.o obj/$game/*.o -o "$out/$game.js" \
    -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createEngine \
    -sENVIRONMENT=worker -sINVOKE_RUN=0 \
    -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=64MB -sSTACK_SIZE=1MB \
    -sEXPORTED_FUNCTIONS=_ein_start,_ein_tick,_ein_join,_ein_key,_ein_button,_ein_wheel,_ein_mouse,_ein_save_config,_ein_set_variable,_ein_menu,_ein_screen,_ein_width,_ein_height,_ein_frames,_ein_audio_render,_malloc,_free \
    -sEXPORTED_RUNTIME_METHODS=FS,HEAPU8,HEAP16,HEAPU32,stringToNewUTF8,UTF8ToString \
    -sFORCE_FILESYSTEM=1 -Wl,--error-limit=0 ${EXTRA_LDFLAGS:-}
  { printf '%s\n' '// deno-fmt-ignore-file' '// deno-lint-ignore-file' '// Generated by engine/build.sh with Emscripten. Do not edit.'; cat "$out/$game.js"; } > "$out/$game.js.new"
  mv "$out/$game.js.new" "$out/$game.js"
done

# The server: Crispy's own, which runs no game and so is the same for the three, with what its files
# call of the network module, the timer and the system (ein_server.c), and the zone allocator on
# malloc, as Crispy's dedicated server has it. It runs in a Deno worker, which Emscripten's web
# runtime suits once it is handed the wasm.
mkdir -p obj/server
server="net_common net_io net_packet net_query net_server net_structrw d_mode m_argv m_misc z_native"
{ for name in $server; do echo "crispy/src/$name.c"; done; echo ein/net_ein.c; echo ein/ein_server.c; } | xargs -P "$jobs" -I{} sh -c \
  'emcc $0 -c "$1" -o "obj/server/$(basename "$1" .c).o"' "$CFLAGS" {}
emcc -O2 obj/server/*.o -o "$out/doom-server.js" \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createDoomServer \
  -sENVIRONMENT=web -sINVOKE_RUN=0 \
  -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=16MB -sSTACK_SIZE=1MB \
  -sEXPORTED_FUNCTIONS=_ein_start,_ein_tick,_ein_status,_ein_left,_malloc,_free \
  -sEXPORTED_RUNTIME_METHODS=HEAPU8,HEAPU32,stringToNewUTF8,UTF8ToString \
  -Wl,--error-limit=0 ${EXTRA_LDFLAGS:-}
{ printf '%s\n' '// deno-fmt-ignore-file' '// deno-lint-ignore-file' '// Generated by engine/build.sh with Emscripten. Do not edit.'; cat "$out/doom-server.js"; } > "$out/doom-server.js.new"
mv "$out/doom-server.js.new" "$out/doom-server.js"
